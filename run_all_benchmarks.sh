#!/bin/bash

# Поднимаем все сервисы в фоновом режиме
echo "Поднимаем окружение Docker..."
docker-compose up -d --build

# Ждем, пока приложение и база данных полностью запустятся.
# Healthcheck в docker-compose помогает, но дополнительная пауза не повредит.
echo "Ожидание готовности сервисов... (30 секунд)"
sleep 30

# Запускаем 100 прогонов
for i in $(seq 1 100); do
  bash ./run_single_test.sh $i
  
  echo "Пауза 10 секунд перед следующим прогоном для стабилизации системы..."
  sleep 10
done

# В конце останавливаем и удаляем все контейнеры вместе с томами
echo "Все тесты завершены. Останавливаем окружение..."
docker-compose down -v

echo "Бенчмаркинг полностью завершен."```
